import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { readFile, writeFile } from "node:fs/promises";
import * as documentSchemas from "@tidy/design/document";
import * as syncSchemas from "@tidy/editor/design/sync-protocol";
const schemas = { ...documentSchemas, ...syncSchemas };
import { objectParserKey } from "../lib/schema-object-parser-key.ts";

const require = createRequire(import.meta.url);
const coreDirectory = dirname(require.resolve("zod/v4/core"));
const { Doc } = await import(join(coreDirectory, "doc.js"));
const original = Doc.prototype.compile;
const factories = new Map();
let generationError;
const seen = new Set();
const objects = [];
function walk(value) {
  if (!value || typeof value !== "object" || seen.has(value)) return;
  seen.add(value);
  if (value._zod) {
    if (value._zod.def.type === "object") objects.push(value);
    walk(value._zod.def);
  } else {
    for (const child of Object.values(value)) walk(child);
  }
}
try {
  Doc.prototype.compile = function () {
    if (this.closed.shape && !this.closed.syms.length) {
      const key = objectParserKey(this.closed.shape, this.closed.memo);
      const source = this.content.join("\n");
      if (factories.has(key) && factories.get(key) !== source) {
        generationError = new Error(
          "Object parser signature does not uniquely identify its source.",
        );
        throw generationError;
      }
      factories.set(key, source);
    }
    return original.call(this);
  };
  for (const schema of Object.values(schemas)) walk(schema);
  for (const schema of objects) {
    try {
      // An object input initializes the complete parser, including absent fields.
      schema._zod.parse({ value: {}, issues: [] }, { async: false });
    } catch {
      // Required defaults/refinements may reject this synthetic input after generation.
    }
  }
} finally {
  Doc.prototype.compile = original;
}
if (generationError) throw generationError;
if (!factories.size) throw new Error("No object parsers were generated.");
const license = await readFile(join(coreDirectory, "../../LICENSE"), "utf8");
const entries = [...factories].sort(([a], [b]) => a.localeCompare(b));
const source = `// Generated by generate-schema-object-parsers.mjs; do not edit.\n/*\n${license}\n*/\nexport const objectParserFactories = new Map([\n${entries
  .map(
    ([key, body]) =>
      `[${JSON.stringify(key)}, (shape, inst, memo) => function(payload, ctx) {\n${body}\n}]`,
  )
  .join(",\n")}\n]);\n`;
const target = new URL("../lib/schema-object-parsers.generated.js", import.meta.url);
if (process.argv.includes("--check")) {
  if ((await readFile(target, "utf8")) !== source)
    throw new Error("Regenerate the object parsers.");
} else {
  await writeFile(target, source);
}
